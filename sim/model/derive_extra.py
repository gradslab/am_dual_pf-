"""Extra symbolic pieces that only need the arm kinematics (fast):
   rho(theta) = R^T (p_e - p_c), J_rho, d = det J_rho, grad_theta d, Hess_theta d.
   Written to am_extra_gen.py"""
import sympy as sp, os

t1, t2, t3 = sp.symbols('th1 th2 th3', real=True)
theta = sp.Matrix([t1, t2, t3])
names = ['mq', 'dm', 'l1', 'm1', 'l2', 'm2', 'l3', 'm3']
mq, dm, l1, m1, l2, m2, l3, m3 = [sp.Symbol(n, positive=True) for n in names]

def Ry(a): return sp.Matrix([[sp.cos(a), 0, sp.sin(a)], [0, 1, 0], [-sp.sin(a), 0, sp.cos(a)]])
def Rz(a): return sp.Matrix([[sp.cos(a), -sp.sin(a), 0], [sp.sin(a), sp.cos(a), 0], [0, 0, 1]])

# body-frame kinematics (R_b = I)
r_m = sp.Matrix([0, 0, -dm])
R1 = Rz(t1); o1 = r_m; c1 = o1 + R1 * sp.Matrix([0, 0, -l1 / 2]); o2 = o1 + R1 * sp.Matrix([0, 0, -l1])
R2 = R1 * Ry(-t2); c2 = o2 + R2 * sp.Matrix([0, 0, -l2 / 2]); o3 = o2 + R2 * sp.Matrix([0, 0, -l2])
R3 = R2 * Ry(-t3); c3 = o3 + R3 * sp.Matrix([0, 0, -l3 / 2]); r_e = o3 + R3 * sp.Matrix([0, 0, -l3])
m = mq + m1 + m2 + m3
r_c = (m1 * c1 + m2 * c2 + m3 * c3) / m
rho = r_e - r_c
J_rho = rho.jacobian(theta)
d = sp.simplify(J_rho.det())
grad = sp.Matrix([d.diff(t) for t in theta])
hess = sp.hessian(d, theta)
print("det J_rho =", d)
print("factor:", sp.factor(d))

flat = list(rho) + list(J_rho) + [d] + list(grad) + list(hess)
reps, red = sp.cse(flat, optimizations='basic')
L = ["# AUTO-GENERATED by derive_extra.py", "import numpy as np", "from math import sin, cos, tan, sqrt, pi", "",
     "def arm_singularity(theta, p):", "    th1, th2, th3 = theta"]
for n in names:
    L.append(f"    {n} = p['{n}']")
for s, e in reps:
    L.append(f"    {s} = {sp.pycode(e, fully_qualified_modules=False)}")
pc = lambda e: sp.pycode(e, fully_qualified_modules=False)
L.append("    rho = np.array([" + ", ".join(pc(e) for e in red[0:3]) + "], dtype=float)")
L.append("    J_rho = np.array([" + ", ".join("[" + ", ".join(pc(e) for e in red[3 + 3 * r:6 + 3 * r]) + "]" for r in range(3)) + "], dtype=float)")
L.append(f"    d = {pc(red[12])}")
L.append("    grad = np.array([" + ", ".join(pc(e) for e in red[13:16]) + "], dtype=float)")
L.append("    hess = np.array([" + ", ".join("[" + ", ".join(pc(e) for e in red[16 + 3 * r:19 + 3 * r]) + "]" for r in range(3)) + "], dtype=float)")
L.append("    return rho, J_rho, d, grad, hess")
L.append("")
L.append("DET_J_RHO_LATEX = r'''" + sp.latex(sp.factor(d)) + "'''")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "am_extra_gen.py")
open(out, "w").write("\n".join(L)); print("wrote", out)
